# ---------------------------------------------------------------- quality


def _ohlcv() -> tuple[Decimal, Decimal, Decimal, Decimal, int]:
    return (Decimal("100"), Decimal("105"), Decimal("99"), Decimal("103"), 1000)


def test_single_source_is_unverified_never_verified() -> None:
    assert quality.assign_quality("test_source", _ohlcv(), []) == "UNVERIFIED"
    # Even a lone official source does not verify itself.
    assert quality.assign_quality("psx_official", _ohlcv(), []) == "UNVERIFIED"


def test_two_agreeing_sources_partially_verified() -> None:
    assert (
        quality.assign_quality("source_b", _ohlcv(), [("source_a", _ohlcv())])
        == "PARTIALLY_VERIFIED"
    )


def test_agreeing_with_official_source_verified() -> None:
    assert (
        quality.assign_quality("source_b", _ohlcv(), [("psx_official", _ohlcv())])
        == "VERIFIED"
    )
    assert (
        quality.assign_quality("psx_official", _ohlcv(), [("source_a", _ohlcv())])
        == "VERIFIED"
    )
    assert (
        quality.assign_quality("source_b", _ohlcv(), [("secp", _ohlcv())]) == "VERIFIED"
    )


def test_disagreeing_sources_conflicted() -> None:
    other = (Decimal("100"), Decimal("105"), Decimal("99"), Decimal("104"), 1000)
    assert quality.assign_quality("source_b", _ohlcv(), [("source_a", other)]) == "CONFLICTED"


def test_stale_rule_boundary() -> None:
    trading = date(2026, 10, 1)
    exactly_30 = datetime(2026, 10, 31, 10, 0, tzinfo=KARACHI)
    day_31 = datetime(2026, 11, 1, 10, 0, tzinfo=KARACHI)
    assert quality.freshness_label(exactly_30, trading) == "CURRENT"
    assert quality.freshness_label(day_31, trading) == "STALE"
    assert quality.freshness_label(None, trading) == "UNKNOWN"
    assert quality.is_stale(day_31, trading) is True
    assert quality.is_stale(exactly_30, trading) is False


