def test_missing_sessions_cover_report_tickers_with_no_rows(db_session) -> None:
    # TESTB has no rows in the file, but is named for the report: its
    # whole requested range must still be listed as missing.
    report = ingestion.ingest_rows(
        db_session,
        [_row()],
        source_key_override="test_source",
        collected_at=datetime(2026, 11, 2, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        date_range=(date(2026, 11, 2), date(2026, 11, 3)),
        dry_run=False,
        report_tickers=["TESTA", "TESTB"],
    )
    assert report.missing_sessions["TESTA"] == ["2026-11-03"]
    assert report.missing_sessions["TESTB"] == ["2026-11-02", "2026-11-03"]
    # Pre-store 2026-11-02 for TESTA from test_source.
    ingestion.ingest_rows(
        db_session,
        [_row()],
        source_key_override="test_source",
        collected_at=datetime(2026, 11, 2, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        dry_run=False,
    )
    source = db_session.query(DataSource).filter_by(source_key="test_source").first()
    security = db_session.query(Security).filter_by(ticker="TESTA").first()
    stored = scheduler.stored_dates_for_source(db_session, source.id, [security.id])
    assert stored[security.id] == {date(2026, 11, 2)}

    validated, _ = ingestion.validate_all(
        [_row(), _row(trading_date="2026-11-03")], {"TESTA", "TESTB"}, today=TODAY
    )
    kept, filtered = scheduler.filter_rows_to_missing(
        validated, stored, {"TESTA": security.id}
    )
    assert filtered == 1
    assert [r.trading_date for r in kept] == [date(2026, 11, 3)]
    assert scheduler.compute_missing_dates(
        {date(2026, 11, 2)}, date(2026, 11, 2), date(2026, 11, 3)
    ) == [date(2026, 11, 3)]
    with pytest.raises(ValueError):
        scheduler.compute_missing_dates(set(), date(2026, 11, 3), date(2026, 11, 2))


