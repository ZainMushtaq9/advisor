def test_two_sources_agreeing_then_disagreeing_side_by_side(db_session) -> None:
    first = ingestion.ingest_rows(
        db_session,
        [_row()],
        source_key_override="source_a",
        collected_at=datetime(2026, 11, 2, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        dry_run=False,
    )
    assert first.quality_breakdown == {"UNVERIFIED": 1}
    agreeing = ingestion.ingest_rows(
        db_session,
        [_row()],
        source_key_override="source_b",
        collected_at=datetime(2026, 11, 2, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        dry_run=False,
    )
    assert agreeing.quality_breakdown == {"PARTIALLY_VERIFIED": 1}
    disagreeing = ingestion.ingest_rows(
        db_session,
        [_row(close="104.00")],
        source_key_override="source_c",
        collected_at=datetime(2026, 11, 2, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        dry_run=False,
    )
    assert disagreeing.quality_breakdown == {"CONFLICTED": 1}
    assert disagreeing.conflicted == 1
    # All three rows stored side-by-side; no winner picked, no overwrite.
    stored = db_session.query(MarketPrice).order_by(MarketPrice.id).all()
    assert len(stored) == 3
    assert [float(p.close_price) for p in stored] == [103.0, 103.0, 104.0]
    assert all(p.is_adjusted is False for p in stored)


