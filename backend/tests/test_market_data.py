def test_stale_rows_counted_in_report(db_session) -> None:
    report = ingestion.ingest_rows(
        db_session,
        [_row()],
        source_key_override="test_source",
        # Collected 2026-11-04 for a 2026-10-01 bar: >30 days -> STALE.
        collected_at=datetime(2026, 11, 4, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        dry_run=False,
    )
    # _row() is dated 2026-11-02, collected 2026-11-04: only 2 days -> not stale.
    assert report.stale == 0
    report2 = ingestion.ingest_rows(
        db_session,
        [_row(trading_date="2026-10-01")],
        source_key_override="test_source",
        collected_at=datetime(2026, 11, 4, 17, 0, tzinfo=KARACHI),
        today=TODAY,
        dry_run=False,
    )
    assert report2.stale == 1
    # Stale is a label in addition to quality, not a replacement.
    assert report2.quality_breakdown == {"UNVERIFIED": 1}
