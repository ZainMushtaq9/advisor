@pytest.fixture()
def db_session(tmp_path):
    engine = create_engine(f"sqlite:///{tmp_path / 'market.db'}")
    Base.metadata.create_all(engine)
    factory = sessionmaker(bind=engine, autoflush=False, autocommit=False)
    session = factory()
    company = Company(legal_name="Test Company A", status="UNVERIFIED")
    session.add(company)
    session.flush()
    # Flush one row at a time: the id fallback reads max(id) at flush
    # time, so two pending rows would otherwise both read the same max.
    session.add(Security(company_id=company.id, ticker="TESTA", status="UNVERIFIED"))
    session.flush()
    session.add(Security(company_id=company.id, ticker="TESTB", status="UNVERIFIED"))
    session.flush()
    session.commit()
    yield session
    session.close()
    engine.dispose()


