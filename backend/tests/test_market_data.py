def _install_sqlite_id_fallback() -> None:
    """TEST ONLY: Phase 3 ids use PostgreSQL Identity, which SQLite
    renders as plain BIGINT PRIMARY KEY with no auto-generation.
    Assign max(id)+1 on insert so the same ORM code runs on a SQLite
    fixture. Production models are untouched; this never runs against
    PostgreSQL (where id is always generated by the database)."""
    for model in (Company, Security, DataSource, MarketPrice):
        def _assign(mapper, connection, target, _model=model):  # noqa: ANN001, ANN202
            if target.id is None:
                value = connection.execute(
                    select(func.max(_model.__table__.c.id))
                ).scalar()
                target.id = (value or 0) + 1

        event.listen(model, "before_insert", _assign)


_install_sqlite_id_fallback()

KARACHI = ZoneInfo("Asia/Karachi")
